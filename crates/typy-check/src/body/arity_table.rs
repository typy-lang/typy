/// Returns the arity of the function `name` of the built-in module `module`.
pub(super) fn function_arity(module: &str, name: &str) -> Option<MethodArity> {
    FUNCTION_ARITIES
        .iter()
        .find(|(each, function, ..)| *each == module && *function == name)
        .copied()
}

/// Returns, for a method or function whose message depends on the number given, the number
/// from which a second message for too many applies, with that message, and the message for
/// each number below the least, which names the argument missing.
pub(super) fn irregular(
    class: &str,
    name: &str,
) -> (Option<(usize, &'static str)>, &'static [&'static str]) {
    match (class, name) {
        ("list", "sort") => (
            Some((3, "sort() takes at most 2 arguments ({} given)")),
            &[],
        ),
        ("math", "prod") => (
            Some((3, "prod() takes at most 2 arguments ({} given)")),
            &[],
        ),
        ("math", "nextafter") => (
            Some((4, "nextafter() takes at most 3 arguments ({} given)")),
            &[],
        ),
        ("math", "isclose") => (
            Some((5, "isclose() takes at most 4 arguments ({} given)")),
            &[
                "isclose() missing required argument 'a' (pos 1)",
                "isclose() missing required argument 'b' (pos 2)",
            ],
        ),
        _ => (None, &[]),
    }
}

