//! The numbers of arguments each method of a built-in type and each function of a built-in
//! module takes, and the `TypeError` CPython 3.15 raises for any other number (EXP-22,
//! ADR-0083). The tables are CPython's own behaviour, read by calling each with zero to eight
//! arguments; a method of a file has the messages of its class, which name it. A few word
//! their message by the number given, which `irregular` adds.

/// An arity: the class of a method's receiver or a function's module, the name, the least and
/// the most positional arguments it takes, `None` for any number, and the messages for too
/// few and too many, `{}` standing for the number given.
type MethodArity = (
    &'static str,
    &'static str,
    usize,
    Option<usize>,
    &'static str,
    &'static str,
);

/// Returns the arity of the method `name` of a value of the class `class`.
pub(super) fn method_arity(class: &str, name: &str) -> Option<MethodArity> {
    METHOD_ARITIES
        .iter()
        .find(|(each, method, ..)| *each == class && *method == name)
        .copied()
}

