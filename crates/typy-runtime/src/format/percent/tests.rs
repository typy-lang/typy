#[test]
fn every_text_conversion_gives_cpythons_text() {
    for (spec, value, expected) in STRS {
        let (value, spec_text) = (from_str(value), from_str(spec));
        // SAFETY: both strings are live.
        let result = unsafe { typy_rt_percent_str(value, spec_text) };
        let found = outcome(result);
        text_of(value);
        text_of(spec_text);
        assert_eq!(found, ok(expected), "%{spec}s");
    }
}

#[test]
fn a_char_of_an_int_gives_cpythons_text_or_overflows() {
    let label = from_str("format argument 2");
    for (spec, digits, expected) in CHARS {
        let (word, spec_text) = (int_word(digits), from_str(spec));
        // SAFETY: the word and the strings are live.
        let result = unsafe { typy_rt_percent_char(word, spec_text, label) };
        let found = outcome(result);
        release_int(word);
        text_of(spec_text);
        assert_eq!(found, ok(expected), "%{spec}c % {digits}");
    }
    for digits in ["-1", "1114112", "1000000000000000000000000000000"] {
        let (word, spec_text) = (int_word(digits), from_str(""));
        // SAFETY: the word and the strings are live.
        let result = unsafe { typy_rt_percent_char(word, spec_text, label) };
        let found = outcome(result);
        release_int(word);
        text_of(spec_text);
        let expected = (
            "OverflowError".to_owned(),
            "format argument 2: %c argument not in range(0x110000)".to_owned(),
        );
        assert_eq!(found, expected, "{digits}");
    }
    text_of(label);
}

#[test]
fn a_char_of_a_str_needs_one_character() {
    let label = from_str("format argument 'k'");
    let wrong = |count: usize| {
        (
            "TypeError".to_owned(),
            format!(
                "format argument 'k': %c requires an integer or a unicode character, not a \
                 string of length {count}"
            ),
        )
    };
    for (value, expected) in [("x", ok("    x")), ("", wrong(0)), ("ab", wrong(2))] {
        let (value, spec_text) = (from_str(value), from_str("5"));
        // SAFETY: the strings are live.
        let result = unsafe { typy_rt_percent_char_str(value, spec_text, label) };
        let found = outcome(result);
        text_of(value);
        text_of(spec_text);
        assert_eq!(found, expected);
    }
    text_of(label);
}

