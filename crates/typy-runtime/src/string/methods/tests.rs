#[test]
fn padding_and_tabs_are_cpython_s() {
    for (whole, width, mode, expected) in PADS {
        // SAFETY: the strings are live.
        let padded =
            unsafe { typy_rt_str_pad(from_str(whole), word(*width), from_str("*"), word(*mode)) };
        assert_eq!(text(padded.value), *expected, "{whole:?} {width} {mode}");
    }
    for (index, (whole, size, expected)) in FILLS.iter().enumerate() {
        // SAFETY: the strings are live.
        let made = unsafe {
            if index < 24 {
                typy_rt_str_zfill(from_str(whole), word(*size))
            } else {
                typy_rt_str_expandtabs(from_str(whole), word(*size))
            }
        };
        assert_eq!(text(made), *expected, "{whole:?} {size}");
    }
    // SAFETY: the strings are live.
    unsafe {
        assert!(
            !typy_rt_str_pad(from_str("a"), word(3), from_str("ab"), word(0))
                .exception
                .is_null()
        );
        assert!(typy_rt_str_isascii(from_str("abc ~")));
        assert!(!typy_rt_str_isascii(from_str("\u{e9}")));
    }
}
