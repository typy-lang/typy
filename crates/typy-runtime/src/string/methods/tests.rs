#[test]
fn searches_find_what_cpython_finds() {
    for (haystack, needle, start, end, flags, expected) in SEARCHES {
        // SAFETY: the strings are live.
        let found = unsafe {
            typy_rt_str_search(
                from_str(haystack),
                from_str(needle),
                word(*start),
                word(*end),
                word(*flags),
            )
        };
        let result = found.exception.is_null().then(|| inline_value(found.value));
        assert_eq!(
            result, *expected,
            "{haystack:?} {needle:?} {start} {end} {flags}"
        );
    }
}

#[test]
fn prefixes_and_suffixes_match_as_cpython_matches_them() {
    for (haystack, affix, start, end, flags, expected) in MATCHES {
        // SAFETY: the strings are live.
        let found = unsafe {
            typy_rt_str_match(
                from_str(haystack),
                from_str(affix),
                word(*start),
                word(*end),
                word(*flags),
            )
        };
        assert_eq!(
            found, *expected,
            "{haystack:?} {affix:?} {start} {end} {flags}"
        );
    }
    let affixes = new_list(ItemKind::Object, 0);
    for affix in ["zz", "wor"] {
        // SAFETY: the list and the string are live.
        unsafe {
            crate::list::typy_rt_list_append(affixes, from_str(affix).expose_provenance() as u64);
        };
    }
    // SAFETY: the list and the strings are live.
    unsafe {
        assert!(typy_rt_str_match_any(
            from_str("hello world"),
            affixes,
            word(6),
            word(0),
            word(1)
        ));
        assert!(!typy_rt_str_match_any(
            from_str("hello"),
            affixes,
            word(0),
            word(0),
            word(0)
        ));
    }
}

