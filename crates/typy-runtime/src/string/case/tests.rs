#[test]
fn case_methods_give_cpython_s_text() {
    for (whole, mode, expected) in CASES {
        // SAFETY: the string is live.
        let made = unsafe { typy_rt_str_case(from_str(whole), inline(*mode).unwrap()) };
        assert_eq!(text(made), *expected, "{whole:?} mode {mode}");
    }
}

#[test]
fn is_methods_give_cpython_s_answers() {
    for (whole, test, expected) in TESTS {
        // SAFETY: the string is live.
        let answer = unsafe { typy_rt_str_test(from_str(whole), inline(*test).unwrap()) };
        assert_eq!(answer, *expected, "{whole:?} test {test}");
    }
}
