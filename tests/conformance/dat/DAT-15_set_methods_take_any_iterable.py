def base() -> set[int]:
    values: set[int] = set()
    for value in [5, 1, 9, 33, 17, 1024, -3, 2 ** 70, 41, 8, 16, 24]:
        values.add(value)
    return values


s = base()
print(s.union(), s.union([7, 64, 1]), s.union([0], (2, 3), set([1024, 4])))
print(s.intersection(), s.intersection([33, 9, 5, 99]), s.intersection([9, 5, 1], s, (1, 9)))
print(s.intersection([16, 8, 24, 41, 2 ** 70, -3, 1024, 17, 33, 9, 1, 5, 7]))
print(s.difference(), s.difference([1, 5]), s.difference((9,), [33], set([17])))
print(s.symmetric_difference([1, 2, 3, 2]), s.symmetric_difference(s))
print(s.issubset([1, 5, 9]), s.issubset(list(s) + [0]), s.issuperset([1, 5]), s.issuperset([0]))
print(s.isdisjoint([100, 200]), s.isdisjoint((1,)), s.isdisjoint(s), set([1]).isdisjoint(set()))
